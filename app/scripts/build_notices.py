"""Write app/Docs/ThirdPartyNotices.md and app/licenses.json from engines.json and models/catalog.json.

    runtime/python/Scripts/python.exe app/scripts/build_notices.py

Nothing listed here is in the repository: the upstream sources, the native programs and the
weights are fetched at installation, each under its own licence. The list is generated so
that it cannot drift from what the Tool actually installs.
"""
import json
from pathlib import Path
import sys

APP = Path(__file__).resolve().parents[1]
OUT = APP / 'Docs' / 'ThirdPartyNotices.md'
#: Extra rows of the Options tab's licence list (the manifest already carries the backends
#: and the models): the upstream sources and the native programs.
OPTIONS = APP / 'licenses.json'


def _cell(value):
    return str(value or '').replace('|', '\\|').replace('\n', ' ').strip() or '—'


def main():
    engines = json.loads((APP / 'engines.json').read_text('utf-8'))['engines']
    catalog = json.loads((APP / 'models' / 'catalog.json').read_text('utf-8'))
    models = catalog.get('models') or catalog
    models = list(models.values()) if isinstance(models, dict) else list(models)

    records = []
    lines = ['# Third-party notices', '',
             'Generated by `app/scripts/build_notices.py` from `app/engines.json` and',
             '`app/models/catalog.json`. None of this is in the repository: everything below is',
             'fetched at installation, under its own licence. A non-commercial licence or a personal',
             'acceptance is shown by the Installation tab for the model concerned.', '',
             '## Upstream sources and native programs', '',
             '| Engine | Project | Origin | Pinned revision | Licence |',
             '|---|---|---|---|---|']
    for engine, spec in engines.items():
        for name, source in (spec.get('sources') or {}).items():
            origin = source.get('repository') or source.get('url') or ''
            lines.append(f'| {engine} | {_cell(name)} | {_cell(origin)} | '
                         f'`{str(source.get("revision", ""))[:12]}` | {_cell(source.get("license"))} |')
            records.append({'kind': 'Source', 'name': f'{name} ({engine})',
                            'license': source.get('license') or 'Not declared', 'url': origin})
        for name, native in (spec.get('natives') or {}).items():
            lines.append(f'| {engine} | {_cell(native.get("label") or name)} | {_cell(native.get("url"))} | '
                         f'binary release | {_cell(native.get("license"))} |')
            records.append({'kind': 'Native program', 'name': native.get('label') or name,
                            'license': native.get('license') or 'Not declared', 'url': native.get('url', '')})

    lines += ['', '## Model weights', '',
              '| Model | Origin | Licence | Personal acceptance |', '|---|---|---|---|']
    for model in sorted(models, key=lambda item: str(item.get('id') or item.get('name'))):
        source = model.get('source') or {}
        origin = source.get('url') or source.get('repository') or model.get('repository') or ''
        gated = source.get('gated') or model.get('gated')
        lines.append(f'| {_cell(model.get("id") or model.get("name"))} | {_cell(origin)} | '
                     f'{_cell(model.get("license") or model.get("licence"))} | {"yes" if gated else "no"} |')

    try:
        # The licence is read from the package actually installed, not written here: a
        # notice must describe the SDK the Tool runs on, whatever a document says.
        from importlib.metadata import metadata
        sdk = metadata('cytools-core')
        sdk_version, sdk_licence = sdk['Version'], sdk.get('License-Expression') or 'see its LICENSE'
    except Exception:  # noqa: BLE001 - the notices must build without the SDK installed
        sdk_version, sdk_licence = '', 'see its LICENSE'
    records.insert(0, {'kind': 'SDK', 'name': f'CyToolsCore {sdk_version}'.strip(), 'license': sdk_licence,
                       'url': 'https://github.com/MrMybal/CyToolsCore'})
    # The interface library is vendored: its origin record says which copy is shipped.
    try:
        cyui = json.loads((APP / 'cyui.json').read_text('utf-8'))
    except (OSError, ValueError):
        cyui = {}
    if cyui:
        records.insert(1, {'kind': 'Interface library', 'name': f"CyUI ({cyui.get('sourceModified', '')})",
                           'license': cyui.get('licence', 'MIT'), 'url': ''})
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from build_release import PARTS, PIP_VERSION  # noqa: E402 - the pins live in one place
    lines += ['', '## Runtime of the Windows binary release', '',
              'Downloaded from their release pages by `app/scripts/build_release.py`, pinned by URL',
              'and SHA-256, and shipped in the `-windows-x64.zip` archive so that it starts on a',
              'machine with nothing installed. Not in the repository; their full licence texts are in',
              'the `LICENCES` folder, with their sources in `LICENCES/SOURCES.txt`.', '',
              '| Part | Origin | Licence |', '|---|---|---|']
    for part in PARTS:
        lines.append(f'| {_cell(part["label"])} | {_cell(part["homepage"])} | {_cell(part["license"])} |')
        records.append({'kind': 'Runtime', 'name': part['label'], 'license': part['license'],
                        'url': part['homepage']})
    lines.append(f'| pip {PIP_VERSION} | https://pip.pypa.io | MIT |')
    lines += ['', '## SDK and Python packages', '',
              f'The Tool is built on the CyToolsCore SDK {sdk_version} ({sdk_licence},',
              'https://github.com/MrMybal/CyToolsCore), installed by `app/requirements.txt` from its',
              'repository; its full licence text is `LICENCES/CyToolsCore-MIT.txt`, and the notice the',
              'scaffold writes is kept as `app/LICENSE-CyToolsCore.txt`. The application environment',
              'and each engine environment',
              '(`app/requirements-engine-*.txt`) are installed from PyPI and the PyTorch index; every',
              'package carries the licence declared on its own page.', '',
              '## Interface library', '',
              'The desktop interface is drawn with CyUI, Cyberalien\'s Dear ImGui library (MIT).',
              '`app/cyui.py` is an unmodified copy of its Python port, recorded with its SHA-256 in',
              '`app/cyui.json`; its licence text is `LICENCES/CyUI-MIT.txt`.', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8')
    OPTIONS.write_text(json.dumps(records, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    print(f'{OUT}: {sum(1 for line in lines if line.startswith("| ") and not line.startswith("| Engine") and not line.startswith("| Model"))} rows')


if __name__ == '__main__':
    main()
